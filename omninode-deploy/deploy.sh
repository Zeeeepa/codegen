install_package() {
  local repo=$1
  local pkg_name=${PKG_NAMES[$repo]}
  local repo_path="${WORKSPACE}/${repo}"

  if [[ ! -d "$repo_path" ]]; then
    log_error "Repository not found: $repo_path"
    return 1
  fi

  log_substep "Installing ${BOLD}${pkg_name}${NC} from ${repo}..."

  cd "$repo_path"

  # Install with uv pip (handles editable installs well)
  if uv pip install -e "." --no-deps 2>/dev/null; then
    log_substep "  ${GREEN}✓${NC} ${pkg_name} installed (no-deps)"
  else
    log_warn "  uv pip failed for ${pkg_name}, trying pip..."
    pip install -e "." --no-deps 2>/dev/null || {
      log_error "  Failed to install ${pkg_name}"
      return 1
    }
  fi
  return 0
}

