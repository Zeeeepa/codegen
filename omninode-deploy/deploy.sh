  log_substep "Starting PostgreSQL, Redpanda, Qdrant, Valkey..."
  cd "$SCRIPT_DIR"
  docker compose up -d postgres redpanda qdrant valkey 2>&1 | tail -5

  # Wait for services to be healthy
  log_substep "Waiting for services to become healthy..."
  TIMEOUT=120
  ELAPSED=0
  while [[ $ELAPSED -lt $TIMEOUT ]]; do
    PG_HEALTHY=$(docker inspect --format='{{.State.Health.Status}}' omninode-postgres 2>/dev/null || echo "unknown")
    RP_HEALTHY=$(docker inspect --format='{{.State.Health.Status}}' omninode-redpanda 2>/dev/null || echo "unknown")
    QD_HEALTHY=$(docker inspect --format='{{.State.Health.Status}}' omninode-qdrant 2>/dev/null || echo "unknown")

    if [[ "$PG_HEALTHY" == "healthy" && "$RP_HEALTHY" == "healthy" && "$QD_HEALTHY" == "healthy" ]]; then
      break
    fi

    printf "\r  Waiting... PG=%s RP=%s QD=%s (%ds/%ds)" "$PG_HEALTHY" "$RP_HEALTHY" "$QD_HEALTHY" "$ELAPSED" "$TIMEOUT"
    sleep 3
    ELAPSED=$((ELAPSED + 3))
  done
  echo ""

  if [[ $ELAPSED -ge $TIMEOUT ]]; then
    log_warn "Some services may not be fully healthy yet (timeout after ${TIMEOUT}s)"
  else
    log_info "All infrastructure services healthy"
  fi

  # Start Redpanda Console (optional monitoring)
  log_substep "Starting Redpanda Console (monitoring UI)..."
  docker compose up -d redpanda-console 2>&1 | tail -1 || true

