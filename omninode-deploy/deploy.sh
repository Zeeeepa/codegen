check_cmd() {
  if command -v "$1" &>/dev/null; then
    local ver
    ver=$($2 2>/dev/null | head -1)
    log_substep "$1: ${GREEN}$ver${NC}"
    return 0
  else
    log_error "$1 not found. $3"
    return 1
  fi
}

