check_cmd docker "docker --version" "Install: https://docs.docker.com/get-docker/" || PREREQS_OK=false
check_cmd python3 "python3 --version" "Install Python 3.12+: https://python.org" || PREREQS_OK=false
check_cmd git "git --version" "Install: apt install git" || PREREQS_OK=false

