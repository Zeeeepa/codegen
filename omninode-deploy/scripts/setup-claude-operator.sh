- ✅ Semantic memory retrieval
- ✅ Pattern compliance enforcement
CLAUDEMD

echo -e "    ${GREEN}✓${NC} CLAUDE.md generated at ${WORKSPACE}/CLAUDE.md"

# =============================================================================
# Step 6: Test emit daemon connectivity
# =============================================================================
echo -e "  ${GREEN}→${NC} Testing emit daemon setup..."

EMIT_WRAPPER="${OMNICLAUDE_DIR}/plugins/onex/hooks/lib/emit_client_wrapper.py"
if [[ -f "$EMIT_WRAPPER" ]]; then
  python "$EMIT_WRAPPER" status --json 2>/dev/null && \
    echo -e "    ${GREEN}✓${NC} Emit daemon reachable" || \
    echo -e "    ${YELLOW}⚠${NC} Emit daemon not running (will start at next SessionStart)"
else
  echo -e "    ${YELLOW}⚠${NC} Emit client wrapper not found (hooks may start daemon on first use)"
fi

# =============================================================================
# Summary
# =============================================================================
echo ""
echo -e "${GREEN}╔══════════════════════════════════════════════════════╗${NC}"
echo -e "${GREEN}║  🤖 Claude Code Operator Integration Complete       ║${NC}"
echo -e "${GREEN}╠══════════════════════════════════════════════════════╣${NC}"
echo -e "${GREEN}║                                                      ║${NC}"
echo -e "${GREEN}║  Hooks:    5 (SessionStart → SessionEnd)             ║${NC}"
echo -e "${GREEN}║  Agents:   54 specialized routing definitions        ║${NC}"
echo -e "${GREEN}║  Skills:   90+ reusable workflows                    ║${NC}"
echo -e "${GREEN}║  Tier:     FULL_ONEX (auto-detected)                 ║${NC}"
echo -e "${GREEN}║                                                      ║${NC}"
echo -e "${GREEN}║  To activate in Claude Code:                         ║${NC}"
echo -e "${GREEN}║    /deploy-local-plugin                              ║${NC}"
echo -e "${GREEN}║                                                      ║${NC}"
echo -e "${GREEN}╚══════════════════════════════════════════════════════╝${NC}"

